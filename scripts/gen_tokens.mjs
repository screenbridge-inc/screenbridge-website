// Generates the brand theme from the design system, so no hex is ever typed by hand.
// Source of truth: screenbridge-agents/design_system/colors_and_type.css
// Writes src/styles/tokens.css (verbatim, font urls pointed at /fonts/) and
// src/styles/tokens.json (token names, read by tailwind.config.js), and copies
// Poppins to public/fonts and the logo lockups to public/brand.
// Usage: node scripts/gen_tokens.mjs [path/to/design_system]
import fs from "node:fs";
import path from "node:path";
import os from "node:os";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const ds = path.resolve(
  process.argv[2] || process.env.SB_DESIGN_SYSTEM || path.join(os.homedir(), "Code/screenbridge-agents/design_system"),
);
const cssPath = path.join(ds, "colors_and_type.css");
if (!fs.existsSync(cssPath)) {
  console.error(`design system not found at ${cssPath}`);
  process.exit(1);
}
let css = fs.readFileSync(cssPath, "utf8");

const fonts = [...css.matchAll(/url\('fonts\/([^']+)'\)/g)].map((m) => m[1]);
css = css.replace(/url\('fonts\//g, "url('/fonts/");

const rootBlock = css.match(/:root\s*{([\s\S]*?)\n}/)[1];
const vars = [...rootBlock.matchAll(/--([a-z0-9-]+)\s*:/g)].map((m) => m[1]);
const colorVars = vars.filter((v) => /^(sb-|bg-|fg-|brand|accent|success|warning|danger|info|border-|divider)/.test(v));

const banner = `/* GENERATED by scripts/gen_tokens.mjs from design_system/colors_and_type.css. Do not edit. */\n`;
fs.writeFileSync(path.join(root, "src/styles/tokens.css"), banner + css);
fs.writeFileSync(
  path.join(root, "src/styles/tokens.json"),
  JSON.stringify({ colors: colorVars, all: vars }, null, 2) + "\n",
);

fs.mkdirSync(path.join(root, "public/fonts"), { recursive: true });
for (const f of new Set(fonts)) fs.copyFileSync(path.join(ds, "fonts", f), path.join(root, "public/fonts", f));
fs.mkdirSync(path.join(root, "public/brand"), { recursive: true });
for (const f of fs.readdirSync(path.join(ds, "assets"))) {
  if (/\.(png|svg|jpe?g|webp)$/i.test(f)) fs.copyFileSync(path.join(ds, "assets", f), path.join(root, "public/brand", f));
}
console.log(`tokens: ${vars.length} vars (${colorVars.length} colors), ${new Set(fonts).size} font files, logos copied`);
